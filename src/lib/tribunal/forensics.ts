export function fold(value: string): string {
  return value
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase();
}

function wordsOf(text: string): string[] {
  return text.trim().length ? text.trim().split(/\s+/) : [];
}

function paragraphsOf(text: string): string[] {
  return text
    .split(/\n+/)
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
}

function sentencesOf(text: string): string[] {
  const flat = text.replace(/\s+/g, " ").trim();
  if (!flat) return [];
  return flat
    .split(/(?<=[.!?])\s+(?=[A-ZÁÉÍÓÚÑ¿«"“])/u)
    .map((part) => part.trim())
    .filter((part) => part.length > 1);
}

function coefficientOfVariation(values: number[]): number {
  if (values.length < 4) return 1;
  const mean = values.reduce((sum, value) => sum + value, 0) / values.length;
  if (mean === 0) return 1;
  const variance =
    values.reduce((sum, value) => sum + (value - mean) ** 2, 0) / values.length;
  return Math.sqrt(variance) / mean;
}

function countPhrase(haystack: string, phrase: string): number {
  if (!phrase) return 0;
  let count = 0;
  let from = 0;
  while (from <= haystack.length) {
    const at = haystack.indexOf(phrase, from);
    if (at === -1) break;
    count += 1;
    from = at + phrase.length;
  }
  return count;
}

export function collectMetaBlob(meta: DocumentMeta): string {
  const bits = [
    meta.title,
    meta.author,
    meta.lastModifiedBy,
    meta.application,
    meta.appVersion,
    meta.producer,
    meta.creator,
    meta.company,
    meta.template,
    meta.keywords,
    meta.subject,
    meta.description,
    ...meta.custom.map((field) => `${field.label} ${field.value}`),
    ...meta.extras.map((field) => `${field.label} ${field.value}`),
  ];
  return fold(bits.filter(Boolean).join(" \n "));
}

function parseTime(value: string | undefined): number | null {
  if (!value) return null;
  const pdf = value.match(
    /D:(\d{4})(\d{2})(\d{2})(\d{2})?(\d{2})?(\d{2})?/i,
  );
  if (pdf) {
    const [, y, mo, d, h = "0", mi = "0", s = "0"] = pdf;
    return Date.UTC(Number(y), Number(mo) - 1, Number(d), Number(h), Number(mi), Number(s));
  }
  const parsed = Date.parse(value);
  return Number.isNaN(parsed) ? null : parsed;
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

export function analyzeText(text: string): TextStats {
  const words = wordsOf(text);
  const sentences = sentencesOf(text);
  const paragraphs = paragraphsOf(text);
  const lengths = sentences.map((sentence) => wordsOf(sentence).length).filter((n) => n > 0);
  const folded = fold(text);
  const transitionHits = PHRASES.map((phrase) => ({
    phrase,
    count: countPhrase(folded, phrase),
  })).filter((hit) => hit.count > 0);
  const citationCount =
    (text.match(
      /\(\s*[A-ZÁÉÍÓÚÑ][\p{L}'’.-]+(?:\s+(?:y|e|&)\s+[A-ZÁÉÍÓÚÑ][\p{L}'’.-]+)?,\s*(?:19|20)\d{2}[a-z]?\s*\)/gu,
    ) ?? []).length +
    (text.match(/\((?:19|20)\d{2}[a-z]?\)/g) ?? []).length;
  const urlCount = (text.match(/https?:\/\/\S+/gi) ?? []).length;
  const bibliographyLikely = /bibliograf[ií]a|referencias\s+bibliogr|works\s+cited|referencias\b/i.test(
    text,
  );
  const firstPerson = (
    folded.match(
      /\b(yo|mi|mis|me|conmigo|nosotros|nosotras|nuestro|nuestra|nuestros|nuestras|creo|pienso|observe|observe|hice|fui|estuve|i|my|we|our)\b/g,
    ) ?? []
  ).length;
  const digitGroups = (text.match(/\d+(?:[.,]\d+)?/g) ?? []).length;
  const markdownResidue =
    /(^|\n)\s{0,3}#{1,6}\s+\S/.test(text) ||
    /\*\*[^*\n]{2,}\*\*/.test(text) ||
    /(^|\n)```/.test(text) ||
    ((text.match(/(^|\n)\s*[-*]\s+\S/g) ?? []).length >= 4);
  const unbackedStudies =
    /diversos estudios|numerosos estudios|estudios han demostrado|research shows|studies have shown/i.test(
      folded,
    ) && citationCount === 0;
  const rigidSkeleton =
    folded.includes("en primer lugar") &&
    folded.includes("en segundo lugar") &&
    (folded.includes("en tercer lugar") ||
      folded.includes("en conclusion") ||
      folded.includes("por ultimo"));
  const avgSentenceWords =
    lengths.length > 0
      ? lengths.reduce((sum, value) => sum + value, 0) / lengths.length
      : 0;

  return {
    chars: text.length,
    words: words.length,
    sentences: sentences.length,
    paragraphs: paragraphs.length,
    avgSentenceWords,
    sentenceLengthCv: coefficientOfVariation(lengths),
    transitionHits,
    transitionTotal: transitionHits.reduce((sum, hit) => sum + hit.count, 0),
    citationCount,
    urlCount,
    bibliographyLikely,
    firstPerson,
    digitGroups,
    markdownResidue,
    unbackedStudies,
    rigidSkeleton,
  };
}

export function analyzeForensics(
  text: string,
  meta: DocumentMeta,
  level: Level,
  brief: string,
): ForensicReport {
  const stats = analyzeText(text);
  const signals: Signal[] = [];
  const blob = collectMetaBlob(meta);
  const folded = fold(text);

  for (const tool of TOOLS) {
    if (tool.needles.some((needle) => blob.includes(needle))) {
      signals.push({
        id: `tool-${tool.id}`,
        severity: "critical",
        weight: 70,
        title: `Metadato de ${tool.label}`,
        detail:
          "El archivo declara una herramienta generativa en el autor, la aplicación, el productor o una propiedad. En esta mesa eso es hallazgo crítico, no un indicio menor.",
      });
    }
  }

  for (const phrase of SELF_ID) {
    if (folded.includes(fold(phrase))) {
      signals.push({
        id: "self-id",
        severity: "critical",
        weight: 60,
        title: "El texto se identifica como salida de un modelo",
        detail: `Aparece la fórmula «${phrase}». No se interpreta como tema de ensayo: es una marca de generación que no se retiró.`,
      });
      break;
    }
  }

  if (stats.words >= 180) {
    const density = stats.transitionTotal / Math.max(stats.words, 1);
    if (stats.transitionTotal >= 18 || (stats.transitionTotal >= 8 && density > 1 / 40)) {
      signals.push({
        id: "transitions-high",
        severity: "high",
        weight: 34,
        title: "Muletillas de prosa generativa",
        detail: `${stats.transitionTotal} apariciones de fórmulas hechas («en la sociedad actual», «cabe destacar», «en conclusión» y afines). Un texto humano también las usa; esta densidad no.`,
      });
    } else if (stats.transitionTotal >= 10 || (stats.transitionTotal >= 6 && density > 1 / 70)) {
      signals.push({
        id: "transitions-high",
        severity: "high",
        weight: 24,
        title: "Muletillas de prosa generativa",
        detail: `${stats.transitionTotal} apariciones de fórmulas hechas («en la sociedad actual», «cabe destacar», «en conclusión» y afines). Un texto humano también las usa; esta densidad no.`,
      });
    } else if (stats.transitionTotal >= 6) {
      signals.push({
        id: "transitions-mid",
        severity: "medium",
        weight: 12,
        title: "Fórmulas de transición repetidas",
        detail: `${stats.transitionTotal} fórmulas típicas de redacción asistida. No cierran el acta solas, pero pesan.`,
      });
    } else if (stats.transitionTotal >= 3) {
      signals.push({
        id: "transitions-low",
        severity: "low",
        weight: 6,
        title: "Algunas fórmulas de manual",
        detail: `${stats.transitionTotal} giros muy frecuentes en textos de modelo. Se anotan, no condenan.`,
      });
    }
  }

  if (stats.rigidSkeleton && stats.words >= 180) {
    signals.push({
      id: "skeleton",
      severity: "high",
      weight: 12,
      title: "Esqueleto en primer, segundo y tercer lugar",
      detail:
        "El texto se organiza como una plantilla de tres bloques más cierre. Es la estructura que un modelo entrega cuando se le pide un ensayo.",
    });
  }

  if (
    stats.words >= 280 &&
    stats.sentences >= 8 &&
    stats.sentenceLengthCv < 0.28 &&
    stats.avgSentenceWords >= 14 &&
    stats.avgSentenceWords <= 32
  ) {
    signals.push({
      id: "burstiness",
      severity: "high",
      weight: 16,
      title: "Cadencia demasiado pareja",
      detail: `Las oraciones duran casi lo mismo (variación ${stats.sentenceLengthCv.toFixed(2)}, media ${stats.avgSentenceWords.toFixed(1)} palabras). La prosa humana suele ser más irregular.`,
    });
  } else if (
    stats.words >= 280 &&
    stats.sentences >= 8 &&
    stats.sentenceLengthCv < 0.38 &&
    stats.avgSentenceWords >= 12 &&
    stats.avgSentenceWords <= 34
  ) {
    signals.push({
      id: "burstiness-mild",
      severity: "medium",
      weight: 8,
      title: "Poca variación entre oraciones",
      detail: `Variación de longitud ${stats.sentenceLengthCv.toFixed(2)}. No es prueba, sí un rasgo de texto pulido de una sola vez.`,
    });
  }

  if (stats.markdownResidue && (meta.source === "docx" || meta.source === "pdf" || meta.source === "paste")) {
    signals.push({
      id: "markdown",
      severity: "high",
      weight: meta.source === "paste" ? 14 : 22,
      title: "Restos de formato de chat",
      detail:
        "Hay marcas de Markdown (títulos con #, negritas ** o listas de chat). Suelen quedar cuando se pega una respuesta de un modelo en el documento.",
    });
  }

  if (stats.unbackedStudies) {
    signals.push({
      id: "unbacked",
      severity: "medium",
      weight: 12,
      title: "«Estudios han demostrado» sin cita",
      detail:
        "Se apela a estudios o autores numerosos y no hay ni una referencia localizable. Es un hueco de rigor y un tic de generación.",
    });
  }

  const wantsVoice =
    level !== "posgrado" ||
    /experienc|opini[oó]n|reflex|relato|yo\b|personal/i.test(brief);
  if (stats.words >= 500 && stats.firstPerson === 0 && wantsVoice) {
    signals.push({
      id: "no-voice",
      severity: "low",
      weight: 8,
      title: "Ninguna marca de primera persona",
      detail:
        "En un texto largo no aparece yo, mi, creo, hicimos ni equivalentes. No es obligatorio en todo género, pero en esta consigna pesa como ausencia de voz.",
    });
  }

  if (stats.words >= 450 && stats.digitGroups === 0) {
    signals.push({
      id: "no-digits",
      severity: "low",
      weight: 6,
      title: "Sin un solo dato concreto",
      detail:
        "No hay cifras, fechas ni cantidades. El texto puede ser correcto y, aun así, no está situado en ningún caso.",
    });
  }

  if (meta.source === "docx" || meta.source === "pdf") {
    const author = fold(meta.author ?? "");
    if (!author) {
      signals.push({
        id: "no-author",
        severity: "medium",
        weight: 10,
        title: "El archivo no tiene autor",
        detail:
          "Word y la mayoría de los PDF guardan quién creó el documento. Un campo vacío en un trabajo largo es una omisión que esta mesa no pasa por alto.",
      });
    } else if (GENERIC_AUTHORS.has(author)) {
      signals.push({
        id: "generic-author",
        severity: "medium",
        weight: 12,
        title: "Autor genérico",
        detail: `El autor declarado es «${meta.author}». No identifica a un estudiante.`,
      });
    }

    if (
      typeof meta.totalTimeMinutes === "number" &&
      Number.isFinite(meta.totalTimeMinutes)
    ) {
      const minutes = meta.totalTimeMinutes;
      if (stats.words >= 300 && minutes <= 1) {
        signals.push({
          id: "time-critical",
          severity: "high",
          weight: 26,
          title: "Tiempo de edición incompatible",
          detail: `El documento declara ${minutes} min de edición para ${stats.words} palabras. Eso no es redactar: es pegar.`,
        });
      } else if (stats.words >= 800 && minutes <= 4) {
        signals.push({
          id: "time-high",
          severity: "high",
          weight: 18,
          title: "Muy poco tiempo de edición",
          detail: `${minutes} min registrados para ${stats.words} palabras. Incluso un texto ya pensado deja más huella al pasarlo a limpio.`,
        });
      } else if (stats.words >= 1200 && minutes <= 10) {
        signals.push({
          id: "time-mid",
          severity: "medium",
          weight: 10,
          title: "Tiempo de edición corto",
          detail: `${minutes} min para ${stats.words} palabras. Se anota como presión, no como cierre.`,
        });
      }
    }

    const created = parseTime(meta.created);
    const modified = parseTime(meta.modified);
    if (created != null && modified != null) {
      const deltaMin = Math.abs(modified - created) / 60000;
      const revision = Number.parseInt(meta.revision ?? "", 10);
      const lowRevision = !meta.revision || revision <= 2;
      if (deltaMin <= 2 && stats.words >= 400 && lowRevision) {
        signals.push({
          id: "timestamps",
          severity: "high",
          weight: 18,
          title: "Creado y modificado casi a la vez",
          detail: `Entre creación y última modificación hay ${deltaMin.toFixed(1)} min, con revisión ${meta.revision ?? "no declarada"}. Un trabajo largo no nace cerrado.`,
        });
      } else if (deltaMin <= 8 && stats.words >= 900 && lowRevision) {
        signals.push({
          id: "timestamps-mild",
          severity: "medium",
          weight: 10,
          title: "Ventana de edición muy breve",
          detail: `${deltaMin.toFixed(0)} min entre creación y modificación. Cabe una exportación rápida; también un pegado.`,
        });
      }
    }

    const producer = fold(`${meta.producer ?? ""} ${meta.creator ?? ""} ${meta.application ?? ""}`);
    const browserPrint = /skia\/pdf|chromium|pdfium|cairo/.test(producer);
    if (browserPrint && !fold(meta.author ?? "")) {
      signals.push({
        id: "browser-print",
        severity: "medium",
        weight: 12,
        title: "PDF impreso desde el navegador, sin autor",
        detail:
          "El productor es el motor de Chrome u otro navegador y no hay autor. Es la firma habitual de «Imprimir» sobre un chat.",
      });
    }

    if (/ilovepdf|smallpdf|soda pdf|sejda|pdfcandy/.test(blob)) {
      signals.push({
        id: "converter",
        severity: "low",
        weight: 6,
        title: "Pasó por un conversor de PDF",
        detail:
          "Esas herramientas reescriben o limpian metadatos. No prueban IA; sí impiden fiarse de lo que el archivo ya no cuenta.",
      });
    }

    const hasProvenance = Boolean(
      meta.author || meta.application || meta.creator || meta.producer || meta.created,
    );
    if (!hasProvenance) {
      signals.push({
        id: "stripped",
        severity: "medium",
        weight: 8,
        title: "Metadatos de procedencia ausentes",
        detail:
          "Un .docx o PDF de procesador suele traer aplicación, autor y fechas. Este no trae casi nada.",
      });
    }
  } else {
    signals.push({
      id: "no-file-meta",
      severity: "info",
      weight: 0,
      title: "Sin metadatos de archivo",
      detail:
        meta.source === "paste"
          ? "El texto se pegó en el formulario. No hay autor, aplicación ni tiempo de edición que inspeccionar. El dictamen descansa en la prosa."
          : "El .txt no guarda cadena de autoría. Si la integridad importa, pida el .docx o el PDF original.",
    });
  }

  if (meta.synthetic) {
    signals.push({
      id: "synthetic",
      severity: "info",
      weight: 0,
      title: "Metadatos de demostración",
      detail:
        "Estos campos no salieron de un archivo del estudiante. Sirven para ver cómo la mesa trata un hallazgo crítico.",
    });
  }

  const smokingGun = signals.some((signal) => signal.severity === "critical");
  const raw = signals.reduce((sum, signal) => sum + signal.weight, 0);
  let score = clamp(raw, 0, 100);
  if (smokingGun) score = Math.max(score, 92);

  return { score, smokingGun, signals, stats };
}
